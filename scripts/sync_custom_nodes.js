// (fix 866) Self-heal for the studio's bundled custom nodes.
//
// install.ps1 copies "custom nodes\*" into <ComfyUI>\ComfyUI\custom_nodes only at
// install time, and the in-app updater (apply_update.ps1) never touches ComfyUI.
// Users who update in-app (e.g. to 7.1.11, which added MiniMaxStudioLoop) end up
// with workflows referencing nodes their ComfyUI has never imported:
//   HTTP 400 missing_node_type, class_type 'MiniMaxStudioLoop'.
//
// Fix: re-sync before EVERY ComfyUI launch. Called from electron/main.js
// (startComfy) and from start.bat. Runs from the freshly updated app files, so
// the fix itself travels inside the update zip - no reinstall needed.
//
// (fix 870) The first version compared a recursive hash of the WHOLE folder and
// replaced the copy when hashes differed. But the user's copy legitimately has
// extra files the bundle doesn't: downloaded ckpts (ComfyUI-Frame-Interpolation
// keeps rife49.pth / film_net_fp32.pt inside its own folder) and __pycache__
// that Python generates at runtime. So hashes never matched, the whole folder
// was deleted and re-copied on every launch - wiping the FPS models, which had
// to be re-downloaded after every restart (user report, 7.1.13).
// Now the sync is a file-level merge: only files that ship in the bundle are
// compared, and only those that differ are overwritten. Nothing extra on the
// user side is ever deleted. Files in the bundle are tiny (<150 KB), so the
// per-file compare is cheap.
//
// (правка 875) The bundle itself was incomplete: "custom nodes\ComfyUI-Frame-
// Interpolation" shipped only vfi_utils.py + vfi_models/film, so the merge
// created a package WITHOUT __init__.py - ComfyUI could not import it and the
// FPS tab died with HTTP 400 missing_node_type ('RIFE VFI'). The full package
// sources (65 .py, no ckpts/images) are now in the bundle.
//
// (правка 924) The bundle still lacked config.yaml: ComfyUI-Frame-Interpolation
// raises "config.yaml file is neccessary" at import, so every VFI node vanished.
// Users who went through 7.1.13 had that file deleted by the whole-folder
// replace (fix 870), and nothing restored it. config.yaml now ships in the
// bundle, but is SEED-ONLY: an existing user copy is never overwritten (see
// SEED_ONLY below). vfi_utils.py also recreates the file at import as a
// fallback, so launching ComfyUI outside the studio keeps working.
//
// Usage: node scripts\sync_custom_nodes.js [comfyRoot]
//        (omitted -> resolved from config\config.ini [comfy] comfy_dir,
//         then %COMFY_ROOT%, then 'ComfyUI' ('ComfyUI-Easy-Install' for
//         installs made before the rename) - same rules as
//         electron/main.js (fix 567) and start.bat).
//
// (правка 905) Раскладка бэкенда: плоская (ядро 0.44+, ставит установщик) -
// <comfyRoot>\main.py, <comfyRoot>\models, <comfyRoot>\custom_nodes,
// <comfyRoot>\python_embeded; и старая - <comfyRoot>\ComfyUI\main.py.
// Каталог ядра определяет resolveComfyCore(); все синхронизации пишут в него.

'use strict'

const { existsSync, readFileSync, readdirSync, statSync, mkdirSync, copyFileSync } = require('node:fs')
const path = require('node:path')

// Generated by Python at runtime - never part of the bundle, never synced.
const SKIP_DIRS = new Set(['__pycache__'])
const SKIP_EXT = /\.(pyc|pyo)$/i

// (правка 924) Файлы-настройки нод: в бандле они есть, но перезаписывать уже
// существующий файл нельзя - пользователь мог его поправить (например,
// ops_backend у Frame-Interpolation). Копируем только когда файла нет. Именно
// этот случай ломал вкладку «FPS» после обновления: у пользователей 7.1.13
// папка ноды была снесена старой самопроверкой вместе с config.yaml, а бандл
// его не содержал - ComfyUI не мог импортировать пакет и отвечал HTTP 400
// missing_node_type 'RIFE VFI'. Ключ - путь внутри custom_nodes через '/'.
const SEED_ONLY = new Set(['ComfyUI-Frame-Interpolation/config.yaml'])

function resolveComfyRoot(appRoot) {
  let configured = ''
  try {
    let section = ''
    for (const line of readFileSync(path.join(appRoot, 'config', 'config.ini'), 'utf8').split(/\r?\n/)) {
      const t = line.trim()
      if (!t || t.startsWith('#') || t.startsWith(';')) continue
      const sec = /^\[([^\]]+)\]$/.exec(t)
      if (sec) { section = sec[1].toLowerCase(); continue }
      const eq = t.indexOf('=')
      if (section === 'comfy' && eq > 0 && t.slice(0, eq).trim().toLowerCase() === 'comfy_dir') {
        configured = t.slice(eq + 1).trim().replace(/"/g, '')
        break
      }
    }
  } catch { /* fall through to env/default */ }
  const raw = configured || (process.env.COMFY_ROOT || '').trim() || defaultComfyRootName(appRoot)
  const primary = path.resolve(appRoot, raw)
  // (правка 905) путь мог указать в несуществующую папку (переименование
  // ComfyUI-Easy-Install -> ComfyUI): ищем установку под известными именами.
  if (existsSync(primary)) return primary
  for (const name of ['ComfyUI', 'ComfyUI-Easy-Install']) {
    const p = path.join(appRoot, name)
    if (existsSync(p)) return p
  }
  return primary
}

/** (правка 905) Имя папки бэкенда по умолчанию: новая ComfyUI; если её нет,
 *  а старая ComfyUI-Easy-Install есть - работаем со старой. */
function defaultComfyRootName(appRoot) {
  const flat = path.join(appRoot, 'ComfyUI')
  const legacy = path.join(appRoot, 'ComfyUI-Easy-Install')
  if (!existsSync(flat) && existsSync(legacy)) return 'ComfyUI-Easy-Install'
  return 'ComfyUI'
}

/** (правка 905) Каталог ядра ComfyUI внутри корня бэкенда: плоская
 *  раскладка - сам корень, старая - <root>\ComfyUI. Если ядра ещё нет,
 *  возвращаем плоский путь (его создаёт установщик 0.44). */
function resolveComfyCore(comfyRoot) {
  if (existsSync(path.join(comfyRoot, 'main.py'))) return comfyRoot
  const legacy = path.join(comfyRoot, 'ComfyUI')
  if (existsSync(path.join(legacy, 'main.py'))) return legacy
  return comfyRoot
}

/** Recursive list of syncable file paths (relative to dir). */
function listFiles(dir, rel = '', out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue
    const p = path.join(dir, name)
    if (statSync(p).isDirectory()) listFiles(p, rel + name + '/', out)
    else if (!SKIP_EXT.test(name)) out.push(rel + name)
  }
  return out
}

/**
 * Merge "<appRoot>\custom nodes\*" into "<comfyCore>\custom_nodes":
 * overwrite changed/missing files from the bundle, keep everything else
 * (user-downloaded ckpts, configs, __pycache__). Never deletes dst files.
 * Returns the names of node packs that had files (re)installed.
 * Never throws on a single pack - failures are reported on stderr.
 */
function syncStudioNodes(appRoot, comfyRoot) {
  const synced = []
  const srcRoot = path.join(appRoot, 'custom nodes')
  const dstRoot = path.join(resolveComfyCore(comfyRoot), 'custom_nodes')
  if (!existsSync(srcRoot) || !existsSync(dstRoot)) return synced
  for (const name of readdirSync(srcRoot)) {
    const src = path.join(srcRoot, name)
    try {
      if (!statSync(src).isDirectory()) continue
      const dst = path.join(dstRoot, name)
      let changed = false
      for (const rel of listFiles(src)) {
        const sp = path.join(src, rel)
        const dp = path.join(dst, rel)
        if (SEED_ONLY.has(`${name}/${rel}`) && existsSync(dp)) continue
        let same = false
        try { same = existsSync(dp) && readFileSync(dp).equals(readFileSync(sp)) } catch { same = false }
        if (same) continue
        mkdirSync(path.dirname(dp), { recursive: true })
        copyFileSync(sp, dp)
        changed = true
      }
      if (changed) synced.push(name)
    } catch (err) {
      console.error(`[custom-nodes] ${name}: ${err && err.message ? err.message : err}`)
    }
  }
  return synced
}

// (правка 904) Ядро ComfyUI перешло на 0.44.0. Наши патчи рассчитаны именно на
// него: файл нод импортирует новые модули ComfyUI, а в 0.44 уже есть то, что мы
// раньше патчили в model.py/model_detection.py (gate_compress, minimax_h3_layout,
// block_index). Если ядро осталось 0.33 (пользователь обновился только внутри
// приложения), патчи класть нельзя - иначе ComfyUI может не запуститься или
// упасть на импорте. В этом случае честно предупреждаем: нужен установщик.
const CORE_MIN_VERSION = '0.44.0'

/** Версия ядра ComfyUI: comfyui_version.py, иначе pyproject.toml. '' - не знаем.
 *  Принимает КАТАЛОГ ЯДРА (resolveComfyCore), а не корень бэкенда. */
function readComfyVersion(comfyCore) {
  const app = comfyCore
  try {
    const txt = readFileSync(path.join(app, 'comfyui_version.py'), 'utf8')
    const m = /__version__\s*=\s*["']([^"']+)["']/.exec(txt)
    if (m) return m[1]
  } catch { /* fall through */ }
  try {
    const txt = readFileSync(path.join(app, 'pyproject.toml'), 'utf8')
    const m = /^version\s*=\s*["']([^"']+)["']/m.exec(txt)
    if (m) return m[1]
  } catch { /* fall through */ }
  return ''
}

/** Сравнение версий вида 0.44.0: <0 - a старее b, 0 - равны, >0 - a новее. */
function compareVersions(a, b) {
  const pa = String(a).split('.').map((n) => parseInt(n, 10) || 0)
  const pb = String(b).split('.').map((n) => parseInt(n, 10) || 0)
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0)
    if (d !== 0) return d
  }
  return 0
}

// (правка 901) Core patches need the same self-heal as custom nodes.
// install.ps1 copies "install\comfy-patches\*" over <ComfyUI>\ComfyUI at install
// time, and the in-app updater never touches ComfyUI. 7.1.17 added the second
// (latent) output to MiniMaxH3AddGuide and the generation workflow now feeds it
// into SamplerCustomAdvanced; on an in-app update the old one-output node stayed
// behind and every audio-guide generation died with HTTP 400:
//   exception_during_inner_validation / IndexError "list index out of range".
// Re-sync the patch files before EVERY ComfyUI launch, same as custom nodes.
function syncCorePatches(appRoot, comfyRoot) {
  const synced = []
  const srcRoot = path.join(appRoot, 'install', 'comfy-patches')
  const dstRoot = resolveComfyCore(comfyRoot)
  if (!existsSync(srcRoot) || !existsSync(dstRoot)) return synced
  // (правка 904) Патчи предназначены для ядра 0.44+. На старом ядре они
  // ломают импорт - лучше не трогать и сказать, что делать.
  const version = readComfyVersion(dstRoot)
  if (version && compareVersions(version, CORE_MIN_VERSION) < 0) {
    console.error(`[comfy-patches] ядро ComfyUI ${version} старее ${CORE_MIN_VERSION}: ` +
      'патчи не применены. Запустите установщик студии, чтобы обновить ядро.')
    return synced
  }
  for (const rel of listFiles(srcRoot)) {
    const sp = path.join(srcRoot, rel)
    const dp = path.join(dstRoot, rel)
    try {
      let same = false
      try { same = existsSync(dp) && readFileSync(dp).equals(readFileSync(sp)) } catch { same = false }
      if (same) continue
      mkdirSync(path.dirname(dp), { recursive: true })
      copyFileSync(sp, dp)
      synced.push(rel)
    } catch (err) {
      console.error(`[comfy-patches] ${rel}: ${err && err.message ? err.message : err}`)
    }
  }
  return synced
}

// (правка 917) Патч VideoHelperSuite: видео без аудиодорожки не должно ронять
// задание. В 0.44 ядро обходит все подключённые выходы ноды через
// comfy.model_patcher.PromptModelTracker.add(), который зовёт .values() на любом
// Mapping, - и ленивое аудио VHS (LazyAudioMap) бросает «VHS failed to extract
// audio» прямо на ноде-загрузчике, до того как его успеет прочитать наш guard.
// Как и comfy-patches, патч доезжает до юзера сам: install.ps1 кладёт его на
// шаге установки нод, а эта функция - при каждом запуске ComfyUI (после
// внутрипрограммного обновления переустановка не нужна).
// Чужой VHS не затираем: файл подменяется, только если это либо целевая версия
// из nodes.json (sha256 в install\vhs-patches\manifest.json), либо уже наш
// пропатченный файл.
const VHS_PATCH_MARKER = '[H3-STUDIO PATCH 917]'

function sha256(buf) {
  return require('node:crypto').createHash('sha256').update(buf).digest('hex')
}

function syncVhsPatches(appRoot, comfyRoot) {
  const synced = []
  const srcRoot = path.join(appRoot, 'install', 'vhs-patches')
  if (!existsSync(srcRoot)) return synced
  let manifest
  try {
    manifest = JSON.parse(readFileSync(path.join(srcRoot, 'manifest.json'), 'utf8'))
  } catch (err) {
    console.error(`[vhs-patch] manifest.json: ${err && err.message ? err.message : err}`)
    return synced
  }
  const nodeDir = path.join(resolveComfyCore(comfyRoot), 'custom_nodes',
    manifest.node_dir || 'comfyui-videohelpersuite')
  // Ноды ещё нет (первая установка) - пропатчит install.ps1 после распаковки.
  if (!existsSync(nodeDir)) return synced
  const upstream = manifest.upstream || {}
  for (const rel of listFiles(srcRoot)) {
    if (rel === 'manifest.json') continue
    const key = rel.replace(/\\/g, '/')
    const sp = path.join(srcRoot, rel)
    const dp = path.join(nodeDir, rel)
    try {
      const want = readFileSync(sp)
      if (existsSync(dp)) {
        const have = readFileSync(dp)
        if (have.equals(want)) continue
        const alreadyPatched = have.includes(Buffer.from(VHS_PATCH_MARKER, 'utf8'))
        const isUpstream = Boolean(upstream[key]) && sha256(have) === String(upstream[key]).toLowerCase()
        if (!alreadyPatched && !isUpstream) {
          console.error(`[vhs-patch] ${key}: файл не совпадает с версией VHS из nodes.json - ` +
            'не трогаем (патч 917 не применён).')
          continue
        }
      }
      mkdirSync(path.dirname(dp), { recursive: true })
      copyFileSync(sp, dp)
      synced.push(key)
    } catch (err) {
      console.error(`[vhs-patch] ${key}: ${err && err.message ? err.message : err}`)
    }
  }
  return synced
}

module.exports = { syncStudioNodes, syncCorePatches, syncVhsPatches, resolveComfyRoot, resolveComfyCore, readComfyVersion, compareVersions }

if (require.main === module) {
  const appRoot = path.resolve(__dirname, '..')
  const comfyRoot = process.argv[2] || resolveComfyRoot(appRoot)
  const synced = syncStudioNodes(appRoot, comfyRoot)
  if (synced.length) console.log('[custom-nodes] installed: ' + synced.join(', '))
  const patched = syncCorePatches(appRoot, comfyRoot)
  if (patched.length) console.log('[comfy-patches] updated: ' + patched.join(', '))
  const vhs = syncVhsPatches(appRoot, comfyRoot)
  if (vhs.length) console.log('[vhs-patch] updated: ' + vhs.join(', '))
}
