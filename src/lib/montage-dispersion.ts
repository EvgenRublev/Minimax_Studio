/**
 * (правка 898) Единая математика радиальной дисперсии для превью монтажки
 * (SVG-фильтр в montage-view) и финального рендера (ffmpeg в /api/montage/render).
 *
 * Зачем: раньше превью смещало каналы на фиксированное число ЭКРАННЫХ пикселей
 * (disp * 1.1), а рендер — на долю КАДРА (коэффициенты k1/k2 lenscorrection).
 * Из-за этого финал выглядел в разы сильнее превью. Теперь обе стороны считают
 * силу по одним и тем же коэффициентам.
 */

/** дисперсия 0..20, маска чистого центра 0..90% */
export function dispersionCoeffs(disp: number, maskPct: number) {
  const m = Math.max(0, Math.min(90, maskPct)) / 100
  const k1 = disp * 0.0024 * Math.max(0.05, 1 - m * 0.9)
  const k2 = disp * 0.0013 * Math.max(0.15, 1 - m * 0.4)
  // (правка 862) запас кадра под смещение кромки: кадр растягивается и режется обратно
  const zoom = Math.min(1.5, 1 + k1 + k2 + 0.01)
  return { k1, k2, zoom }
}

/**
 * Максимальное смещение канала (в углах кадра) как ДОЛЯ ПОЛУДИАГОНАЛИ готового
 * кадра. В превью умножается на полудиагональ элемента в CSS px — так сила
 * перестаёт зависеть от размера окна.
 *
 * maskPct в рендере работает как приглушение силы: чем больше «маска центра»,
 * тем меньше k1/k2 (профиль линзы и так даёт ~0 смещения у центра).
 */
export function dispersionMaxShift(disp: number, maskPct: number): number {
  const { k1, k2, zoom } = dispersionCoeffs(disp, maskPct)
  const z2 = zoom * zoom
  return k1 / z2 + k2 / (z2 * z2)
}
